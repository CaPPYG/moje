# --- Zostavenie prikazu pre yt-dlp ---------------------------------------------

def build_cmd(link, cfg):
    cmd = ["yt-dlp"]

    # Vystupny vzor (povodny prieinok sa zachova: uploader_id)
    out = cfg.out or DEFAULT_OUT
    cmd += ["-o", os.path.join(out, "%(uploader)s_%(id)s.%(ext)s")]

    cmd += [
        "--no-playlist",   # stiahnut len to video, nie cely zoznam
        "--ignore-errors", # nema vymriet pri jednom chybnom linku
        "--newline",       # kazdy riadok logu na novy riadok (citelne)
        "--retries", "5",
        "--fragment-retries", "5",
        "--no-part",       # nechat finalny subor bez .part je cistejsie
    ]

    # -- Obmedzene / age-restricted videa -----------------------------------
    # povolit akykolvek vek: 18+ / "pre urcite publikum" uz nespadne ako chyba
    cmd += ["--age-limit", str(cfg.age_limit)]

    # prihlasene cookies = kluc k obmedzenemu obsahu (najcastejsia oprava)
    if cfg.cookies:
        cmd += ["--cookies", ensure_netscape_cookies(cfg.cookies)]
    elif cfg.browser:
        # yt-dlp vezme cookies priamo z prehliadaca
        cmd += ["--cookies-from-browser", cfg.browser]

    # alternativny player client pomaha obist "Sign in to confirm / not a bot"
    if cfg.player_client:
        cmd += ["--extractor-args", f"youtube:player_client={cfg.player_client}"]

    if cfg.proxy:
        cmd += ["--proxy", cfg.proxy]

    if cfg.extra:
        cmd += [a for a in cfg.extra.split() if a]

    # JS runtime (deno) zlepsuje extrakciu/deciphering na YouTube (age-gated formaty)
    # yt-dlp ho autodetekuje v PATH; ak je k dispozicii, explicitne ho zadame
    if shutil.which("deno") and "--js-runtimes" not in cmd:
        cmd += ["--js-runtimes", "deno"]


    cmd.append(link)
    return cmd


# --- Stiahnutie jedneho linku --------------------------------------------------

def download(link, cfg):
    cmd = build_cmd(link, cfg)
    print(f"\n[>] {link}")
    print("   " + " ".join(cmd))

    try:
        r = subprocess.run(cmd, capture_output=True, text=True)
    except Exception as e:
        print(f"   [X] Spustenie zlyhalo: {e}")
        return False

    if r.returncode == 0:
        print("   [OK]")
        return True

    # chybova hlaska (posledne riadky stderr)
    tail = [ln for ln in (r.stderr or "").splitlines() if ln.strip()]
    last = tail[-1] if tail else "nezname chyba"
    print(f"   [X] {last}")

    hint = hint_for_error(r.stderr or "")
    if hint:
        print(f"   [i] {hint}")
    return False



def hint_for_error(stderr):
    s = (stderr or "").lower()
    if "sign in" in s or ("age" in s and "restrict" in s) or "confirm your age" in s:
        return "Video je vekovo/targetovane obmedzene. Spusti s --browser chrome (alebo ten, kde si prihlaseny), aby sa pouzili tvoje cookies."
    if "not available in your" in s or "geo" in s or "region" in s:
        return "Video nie je dostupne pre tvoju krajinu - skus --proxy alebo inu IP."
    if "not a bot" in s or "bot" in s:
        return "YouTube Bot-check. Pouzi --browser chrome (prihlaseny) alebo --player-client."
    if "private" in s or "unavailable" in s or "removed" in s:
        return "Video je sukromne / odstrvene / nedostupne - neda sa stiahnut."
    if "login" in s or "oauth" in s or "cookies" in s:
        return "Potrebuje prihlasenie. Pouzi --cookies-from-browser <browser>."
    if "javascript runtime" in s or "js runtime" in s or "--js-runtimes" in s or "deprecated" in s:
        return "YouTube vyzaduje JS runtime. Nainstaluj deno (napr. npm i -g deno), potom skus znova − zlepsi extrakciu obmedzenych/age-gated formatov."

    return "Chyba moze byt docasna - skus to znova, pripadne aktualizuj yt-dlp:  yt-dlp -U"


# --- Main ----------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(
        description="Reels downloader cez yt-dlp (riesi obmedzene videa)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__)
    p.add_argument("-l", "--links", nargs="*", default=[],
                   help="Zoznam URL. Ak vynasas, cita links.txt.")
    p.add_argument("--out", default=DEFAULT_OUT, help="Vystupny prieinok (default: ~/Downloads/reels)")
    p.add_argument("--browser", default=None, choices=BROWSERS,
                   help="Prehliadac s prihlasenim, odkial brat cookies")
    p.add_argument("--cookies", default=None,
                   help="cookies.txt (Netscape) alebo JSON export z Cookie-Editor/EditThisCookie (premeni sa automaticky)")
    p.add_argument("--age-limit", type=int, default=100,
                   help="Max. vek (default 100 = povolit 18+/obmedzene)")
    p.add_argument("--player-client", default="default,tv",
                   help="YouTube player client (napr. default,tv - pomaha s bot/age check)")
    p.add_argument("--proxy", default=None, help="Proxy URL")
    p.add_argument("--extra", default=None, help="Dalsie flagy pre yt-dlp (cely retazec)")
    cfg = p.parse_args()

    if not check_tools():
        return 1

    os.makedirs(cfg.out, exist_ok=True)

    links = read_links(cfg)
    if not links:
        print("[X] Ziadne linky. Vloz ich do links.txt alebo pouzi -l 'URL'.")
        return 1

    ok = fail = 0
    for link in links:
        if download(link, cfg):
            ok += 1
            drop_from_links(link)   # uspesne stiahnuty -> prec z links.txt
        else:
            fail += 1

    print(f"\n[F] Hotovo -> OK {ok}  X {fail}   |   prieinok: {cfg.out}")
    return 0 if fail == 0 else 2


if __name__ == "__main__":
    sys.exit(main())


