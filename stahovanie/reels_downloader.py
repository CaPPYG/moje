#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Reels Downloader (yt-dlp) - robustna verzia.
============================================
Opravuje situaciu: "ked je video obmedzene pre urcite publikum nejde stiahnut".

Co riesi oproti starej verzii:
  * age-restricted / 18+ / "not available in your country" / bot check
    -> pouziva prihlasene cookies + --age-limit + alternativny player client
  * nezastavi sa pri jednom chybnom linku -> pokracuje dalej
  * prehladny log + jasna chybova hlaska + napoveda pre bezne chyby
  * PO uspesnom stiahnuti sa link AUTOMATICKY odstrani z links.txt
  * spustenie:
        python reels_downloader.py                  # cita links.txt
        python reels_downloader.py -l "URL1" "URL2"
        python reels_downloader.py --browser chrome --out C:\\reels
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

DEFAULT_OUT = os.path.join(os.path.expanduser("~"), "Downloads", "reels")
LINKS_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "links.txt")

# Najbeznejsie prehliadace, z ktorych vieme zobrat prihlasene cookies.
BROWSERS = [
    "chrome", "chromium", "edge", "firefox", "opera", "brave",
    "vivaldi", "safari",
]


# --- Pomocne funkcie -----------------------------------------------------------

def tool(name):
    """Vrati True, ak je nastroj (yt-dlp/ffmpeg) dostupny v PATH."""
    return shutil.which(name) is not None


def check_tools():
    missing = [n for n in ("yt-dlp", "ffmpeg") if not tool(n)]
    if missing:
        print(f"[X] Chyba: {', '.join(missing)}")
        print("   Nainstaluj:  pip install -U yt-dlp   (ffmpeg daj do PATH)")
        return False
    return True


def normalize_link(line):
    line = (line or "").lstrip("\ufeff").strip()  # BOM (UTF-8 BOM) ignoruj
    if not line or not re.match(r"^https?://", line):
        return None
    return line


def read_links(args):
    links = []

    # 1) linky z argumentov
    for l in (args.links or []):
        n = normalize_link(l)
        if n and n not in links:
            links.append(n)

    # 2) linky zo suboru links.txt (v priecku tohto skriptu)
    if not links and os.path.isfile(LINKS_FILE):
        with open(LINKS_FILE, "r", encoding="utf-8") as f:
            for line in f:
                n = normalize_link(line)
                if n and n not in links:
                    links.append(n)

    return links


def drop_from_links(link):
    """Po uspesnom stiahnuti odstrani dany link z links.txt (ak tam je)."""
    if not os.path.isfile(LINKS_FILE):
        return False
    target = normalize_link(link)
    if target is None:
        return False
    with open(LINKS_FILE, "r", encoding="utf-8") as f:
        lines = f.readlines()
    kept = []
    removed = False
    for ln in lines:
        if normalize_link(ln) == target:
            removed = True
            continue
        kept.append(ln)
    if removed:
        with open(LINKS_FILE, "w", encoding="utf-8", newline="") as f:
            f.writelines(kept)
        print(f"   [~] Odstranene z links.txt: {link}")
    return removed


# --- Cookies: JSON (Cookie-Editor / EditThisCookie) -> Netscape format ----------

def json_cookies_to_netscape(json_path, out_path):
    """Prevedie cookies export v JSON (pole objektov) na Netscape cookies.txt."""
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    lines = ["# Netscape HTTP Cookie File", "# Generated by reels_downloader.py"]
    if isinstance(data, dict) and "cookies" in data:
        data = data["cookies"]  # niektoré exporty balia do {"cookies":[...]}
    for c in data:
        if not isinstance(c, dict):
            continue
        domain = c.get("domain", "")
        host_only = c.get("hostOnly", False)
        flag = "TRUE" if not host_only else "FALSE"
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        exp = 0
        if not c.get("session") and c.get("expirationDate"):
            try:
                exp = int(float(c["expirationDate"]))
            except (TypeError, ValueError):
                exp = 0
        name = c.get("name", "")
        value = c.get("value", "")
        if not domain or not name:
            continue
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{exp}\t{name}\t{value}")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return out_path


def ensure_netscape_cookies(cookies_path):
    """Ak je cookies subor v JSON (Cookie-Editor), prevedie ho na Netscape."""
    if not os.path.isfile(cookies_path):
        return cookies_path
    with open(cookies_path, "r", encoding="utf-8", errors="ignore") as f:
        head = f.read(256).lstrip()
    if head.startswith("["):
        base = os.path.splitext(cookies_path)[0]
        out = base + ".cookies.txt"
        try:
            json_cookies_to_netscape(cookies_path, out)
            print(f"   [~] Cookies JSON -> {os.path.basename(out)}")
            return out
        except Exception as e:
            print(f"   [i] Cookies JSON konverzia zlyhala ({e}) – pouzijem subor priamo.")
            return cookies_path
    return cookies_path


